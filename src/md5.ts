const rotl = (x: number, c: number): number => ((x << c) | (x >>> (32 - c))) >>> 0;
const add = (x: number, y: number): number => (x + y) >>> 0;

/** Lowercase hex md5 of a byte array. */
export function md5Hex(bytes: Uint8Array): string {
  const len = bytes.length;
  const bitLen = len * 8;
  const paddedLen = (((len + 8) >> 6) + 1) << 6;

  const buf = new Uint8Array(paddedLen);
  buf.set(bytes, 0);
  buf[len] = 0x80;
  const dv = new DataView(buf.buffer);
  dv.setUint32(paddedLen - 8, low32(bitLen), true);
  dv.setUint32(paddedLen - 4, high32(bitLen), true);

  let a0 = 0x67452301;
  let b0 = 0xefcdab89;
  let c0 = 0x98badcfe;
  let d0 = 0x10325476;

  const words = new Uint32Array(16);
  for (let offset = 0; offset < paddedLen; offset += 64) {
    for (let i = 0; i < 16; i++) {
      words[i] = dv.getUint32(offset + i * 4, true);
    }

    let a = a0;
    let b = b0;
    let c = c0;
    let d = d0;

    for (let i = 0; i < 64; i++) {
      let f: number;
      let g: number;
      if (i < 16) {
        f = (b & c) | (~b & d);
        g = i;
      } else if (i < 32) {
        f = (d & b) | (~d & c);
        g = (5 * i + 1) & 15;
      } else if (i < 48) {
        f = b ^ c ^ d;
        g = (3 * i + 5) & 15;
      } else {
        f = c ^ (b | ~d);
        g = (7 * i) & 15;
      }
      const tmp = add(add(add(a, f), K[i]!), words[g]!);
      a = d;
      d = c;
      c = b;
      b = add(b, rotl(tmp, S[i]!));
    }

    a0 = add(a0, a);
    b0 = add(b0, b);
    c0 = add(c0, c);
    d0 = add(d0, d);
  }

  const out = new Uint8Array(16);
  new DataView(out.buffer).setUint32(0, a0, true);
  new DataView(out.buffer).setUint32(4, b0, true);
  new DataView(out.buffer).setUint32(8, c0, true);
  new DataView(out.buffer).setUint32(12, d0, true);

  return Array.from(out)
    .map((byte) => byte.toString(16).padStart(2, '0'))
    .join('');
}

function low32(bitLen: number): number {
  return bitLen >>> 0;
}

function high32(bitLen: number): number {
  return Math.floor(bitLen / 0x100000000);
}